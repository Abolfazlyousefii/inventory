const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const source=readFileSync('resources/views/products/partials/bundle-create.blade.php','utf8');
const code=source.slice(source.indexOf('function selectItems('),source.indexOf('function selectionLabel('));
assert.ok(code.includes('function choose('));
const selected=new Map();
const context={selected,refresh(){},hide(){},search:{value:'',focus(){}},alert(message){throw new Error(message);}};
vm.createContext(context);vm.runInContext(code,context);
const rows=Array.from({length:6001},(_,n)=>({id:n+1,name:'Component '+n}));
context.selectItems(rows,true);
assert.equal(selected.size,6001);
context.selectItems(rows,true);
assert.equal(selected.size,6001,'Repeated group selection must not duplicate variants');
context.selectItems([rows[100]],false);
assert.equal(selected.size,6000);
context.choose(rows[100]);
assert.equal(selected.size,6001,'Individual selection must work past the old limits');
assert.equal(selected.get(101).quantity,1);
console.log('Bundle selection: 6001 variants, repeat selection, removal and individual re-add passed.');
